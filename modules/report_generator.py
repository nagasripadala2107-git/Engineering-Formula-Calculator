from datetime import datetime

class ReportGenerator:
    """
    Generates standardized academic lab and assignment reports in Markdown and printable format.
    """

    @staticmethod
    def generate_markdown_report(student_name, roll_no, subject, problem_title, inputs_dict, steps_list, result_str):
        date_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        
        lines = [
            f"# 📄 Academic Lab Computation Report",
            f"**Generated:** {date_str}  ",
            f"**Institution Curriculum:** JNTUK R23 B.Tech Engineering  ",
            f"",
            f"---",
            f"### 👤 Student Details",
            f"- **Student Name:** {student_name if student_name else 'N/A'}",
            f"- **Roll Number:** {roll_no if roll_no else 'N/A'}",
            f"- **Subject Module:** {subject}",
            f"",
            f"---",
            f"### 🎯 Problem Statement",
            f"**Experiment / Solver:** {problem_title}",
            f"",
            f"#### 📥 Given Input Parameters:",
        ]
        
        for k, v in inputs_dict.items():
            lines.append(f"- **{k}:** `{v}`")
            
        lines.extend([
            f"",
            f"---",
            f"### 🧮 Step-by-Step Derivation & Formula Substitution",
        ])
        
        for idx, step in enumerate(steps_list, 1):
            lines.append(f"{idx}. {step}")
            
        lines.extend([
            f"",
            f"---",
            f"### 🏆 Final Verified Output",
            f"```text",
            f"{result_str}",
            f"```",
            f"",
            f"---",
            f"*Certified Computation generated by Engineering Formula Calculator & AI Assistant.*"
        ])
        
        return "\n".join(lines)
